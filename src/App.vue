<script setup lang="ts">
import { computed, onMounted, reactive, ref, watch, inject} from 'vue'
import { watchDebounced } from '@vueuse/core'
import { useVuelidate } from '@vuelidate/core'
import { url } from '@vuelidate/validators'
import {
  DialogClose,
  DialogContent,
  DialogOverlay,
  DialogPortal,
  DialogRoot,
  DialogTitle,
  PopoverAnchor,
  PopoverArrow,
  PopoverContent,
  PopoverPortal,
  PopoverRoot,
  ProgressIndicator,
  ProgressRoot,
  SliderRange,
  SliderRoot,
  SliderThumb,
  SliderTrack
} from 'reka-ui'
import { PhCaretDown, PhCaretUp, PhCheckCircle, PhX } from '@phosphor-icons/vue'
import BaseButton from './components/form-controls/BaseButton.vue'
import ToggleSwitch from './components/form-controls/ToggleSwitch.vue'

type Monitor = { name: string; status: string; percentage: number }
type SortOrder = 'ascending' | 'descending'

const counter = reactive([0, 0])
const sliderCount = ref(0)
const confidenceLevel = ref(77)
const message = ref('')
const numClicks = ref(0)
const distraction = ref(false)
const checkedMessages = reactive<Array<string>>([])
const checkDone = ref(false)
const main = ref()
const darkMode = inject("darkMode", ref(false))
const dialogVisible = ref(false)


const state = reactive({
  urlToCheck: ''
})

const data = reactive(new Array<Monitor>())

for (let n = 0; n < 100; n++) {
  data.push({
    name: 'Data',
    status: 'Possibly Ok',
    percentage: 84
  })
}

const columns: Array<{ key: keyof Monitor; label: string }> = [
  { key: 'name', label: 'Monitor' },
  { key: 'status', label: 'Status' },
  { key: 'percentage', label: '%' }
]
const sort = ref<{ key: keyof Monitor; order: SortOrder } | null>(null)

const sortedData = computed(() => {
  if (!sort.value) return data
  const { key, order } = sort.value
  const direction = order === 'ascending' ? 1 : -1
  return [...data].sort((a, b) => (a[key] > b[key] ? direction : a[key] < b[key] ? -direction : 0))
})

const formattedConfidenceLevel = computed(() => {
  if (confidenceLevel.value >= 73) {
    return '!'
  } else if (confidenceLevel.value >= 29) {
    return '.'
  } else {
    return '?'
  }
})

const services = ['ping', 'dns', 'network', 'dns', 'ssl', 'cpu', 'memory', 'disk space']

const others = [
  'Passport',
  'Safety Equipment',
  'First Aid Kit',
  'Vehicle Maintenance',
  'Home Appliances',
  'Smoke Alarms',
  'Emergency Exits',
  'Food Expiry Dates',
  'Travel Itinerary'
]

function doCheck(n: number) {
  if (n === 0) {
    checkedMessages.splice(0)
    checkDone.value = false
  }
  let tocheck = v$.value.urlToCheck.$invalid ? others : services
  let verb = v$.value.urlToCheck.$invalid ? (s: string) => (s.endsWith('s') ? 'are' : 'is') : 'is'

  const timeout = Math.random() * 3000 + 1000
  let info = ''
  if (tocheck[n] === 'dns' && n > 1) {
    info = " (again, it's important!)"
  }

  let last = checkedMessages.push(`Checking ${tocheck[n]}${info} ...`) - 1

  setTimeout(() => {
    checkedMessages[last] = `${tocheck[n]} ${
      verb instanceof Function ? verb(tocheck[n]) : verb
    } Possibly Ok!`
    setTimeout(() => {
      n++
      if (n < tocheck.length) doCheck(n)
      else {
        checkDone.value = true
      }
    }, timeout)
  }, timeout)
}

function transform(button: number) {
  const sign = numClicks.value > 20 ? -1 : 1
  return `scale(${sign * (1 + counter[button] / 10)}, ${1 + counter[button] / 10})`
}

function click(button: number) {
  numClicks.value++
  counter[button]++
  if (button === 0) {
    counter[1] = 0
  } else {
    counter[0] = 0
  }
}

function updateConfidenceLevel(values: number[] | undefined) {
  if (values) confidenceLevel.value = values[0]
}

function isSorted(key: keyof Monitor, order: SortOrder) {
  return sort.value?.key === key && sort.value.order === order
}

function toggleSort(key: keyof Monitor) {
  if (sort.value?.key !== key) {
    sort.value = { key, order: 'ascending' }
  } else if (sort.value.order === 'ascending') {
    sort.value = { key, order: 'descending' }
  } else {
    sort.value = null
  }
}

watchDebounced(
  confidenceLevel,
  () => {
    sliderCount.value++
  },
  { debounce: 500, immediate: true }
)

watch(sliderCount, () => {
  if (sliderCount.value > 10) {
    message.value = 'You got that slider business under control!'
    if (counter.every((n) => n === 0)) {
      message.value += ' Maybe you should try the buttons now?'
    } else {
      message.value += ' You should try the buttons again!'
    }
  } else if (sliderCount.value > 7) {
    message.value = 'You are very good at using the slider. Keep going!'
  } else if (sliderCount.value > 3) {
    message.value = 'You are getting the hang of it!'
  }
})

watch(
  () => counter,
  () => {
    if (counter.some((n) => n >= 10)) {
      sliderCount.value = 0
      message.value = ''
    }
  },
  { deep: true }
)

const rules = {
  urlToCheck: { url }
}
const v$ = useVuelidate(rules, state)

onMounted(() => {
  const root = document.documentElement
  root.addEventListener('mousemove', (evt) => {
    let x = evt.clientX + window.scrollX
    let y = evt.clientY + window.scrollY

    root.style.setProperty('--mouse-x', `${x}px`)
    root.style.setProperty('--mouse-y', `${y}px`)
  })

  setTimeout(() => {
    dialogVisible.value = true
  }, 1000 * 20)

})

watch(darkMode, () => {
  if (darkMode.value) {
    document.getElementById("app")?.classList.add("darkMode")
  } else {
    document.getElementById("app")?.classList.remove("darkMode")
  }


})
</script>
