    </div>

    <div class="flex justify-center" style="margin-top: 2em">
      <div class="w-full min-[1200px]:w-1/2">
        <h3>With Ok!-Bot, you can monitor anything that is important to you:</h3>
        <div class="h-[250px] overflow-auto text-sm text-text-regular">
